<?php
namespace PlayBrick\Tests;

use PHPUnit\Framework\TestCase;

class BricksSourceTest extends TestCase {

	private function rmdir( string $dir ): void {
		if ( ! is_dir( $dir ) ) {
			return;
		}

		$items = new \RecursiveIteratorIterator(
			new \RecursiveDirectoryIterator( $dir, \RecursiveDirectoryIterator::SKIP_DOTS ),
			\RecursiveIteratorIterator::CHILD_FIRST
		);

		foreach ( $items as $item ) {
			$path = $item->getPathname();
			if ( $item->isDir() ) {
				rmdir( $path );
			} else {
				unlink( $path );
			}
		}

		rmdir( $dir );
	}

	protected function tearDown(): void {
		$this->rmdir( sys_get_temp_dir() . '/playbrick-bricks-source' );
		parent::tearDown();
	}

	public function test_extracts_local_global_and_attribute_classes_from_bricks_data(): void {
		$data = [
			[
				'settings' => [
					'_cssClasses'       => 'bg-red-500 md:hover:text-white',
					'_cssGlobalClasses' => [ 'abc123' ],
					'_attributes'       => [
						[ 'name' => 'class', 'value' => 'custom-attr-class px-4' ],
					],
				],
			],
		];

		$classes = playbrick_extract_classes_from_bricks_data( $data, [ 'abc123' => 'eq-button' ] );

		$this->assertSame(
			[ 'bg-red-500', 'custom-attr-class', 'eq-button', 'md:hover:text-white', 'px-4' ],
			$classes
		);
	}

	public function test_write_bricks_tailwind_source_creates_generated_html(): void {
		$playground = sys_get_temp_dir() . '/playbrick-bricks-source/playground';

		$path = playbrick_write_bricks_tailwind_source( $playground, [ 'px-4', 'bg-red-500', 'px-4', '[&>*]:mt-4', "before:content-['']", "bad class" ], '.t-c1 { @apply bg-red-500; }' );

		$this->assertSame( $playground . '/.playbrick/bricks-sources.html', $path );
		$this->assertFileExists( $path );
		$this->assertFileExists( $playground . '/.playbrick/bricks-sources.txt' );
		$this->assertFileExists( $playground . '/.playbrick/bricks-custom.css' );

		$contents = file_get_contents( $path );
		$this->assertStringContainsString( 'Generated by PlayBrick', $contents );
		$this->assertStringContainsString( 'bg-red-500', $contents );
		$this->assertStringContainsString( '[&amp;&gt;*]:mt-4', $contents );

		$raw_contents = file_get_contents( $playground . '/.playbrick/bricks-sources.txt' );
		$this->assertStringContainsString( '[&>*]:mt-4', $raw_contents );
		$this->assertStringContainsString( "before:content-['']", $raw_contents );
		$this->assertStringNotContainsString( 'bad class', $raw_contents );

		$custom_css = file_get_contents( $playground . '/.playbrick/bricks-custom.css' );
		$this->assertStringContainsString( '.t-c1 { @apply bg-red-500; }', $custom_css );
	}

	public function test_normalizes_bare_custom_css_for_tailwind_apply(): void {
		$css = playbrick_normalize_tailwind_custom_css_block( "@apply bg-red-500\ncolor: white;", '.t-c1' );

		$this->assertStringContainsString( '.t-c1 {', $css );
		$this->assertStringContainsString( '@apply bg-red-500;', $css );
		$this->assertStringContainsString( 'color: white;', $css );
	}

	public function test_wraps_mobile_portrait_custom_css_in_default_bricks_media_query(): void {
		$css = playbrick_normalize_tailwind_custom_css_block( '@apply text-xs;', '.font-title', '_cssCustom:mobile_portrait' );

		$this->assertStringContainsString( '@media (max-width: 478px) {', $css );
		$this->assertStringContainsString( ".font-title {\n  @apply text-xs;\n}", $css );
		$this->assertLessThan( strpos( $css, '.font-title {' ), strpos( $css, '@media (max-width: 478px) {' ) );
	}

	public function test_leaves_default_desktop_custom_css_unwrapped(): void {
		$css = playbrick_normalize_tailwind_custom_css_block( '@apply text-5xl;', '.font-title', '_cssCustom' );

		$this->assertStringContainsString( ".font-title {\n  @apply text-5xl;\n}", $css );
		$this->assertStringNotContainsString( '@media', $css );
	}

	public function test_skips_unknown_breakpoint_instead_of_leaking_custom_css(): void {
		$css = playbrick_normalize_tailwind_custom_css_block( '@apply text-xs;', '.font-title', '_cssCustom:unknown' );

		$this->assertStringContainsString( 'Skipped unresolved Bricks breakpoint: _cssCustom:unknown', $css );
		$this->assertStringNotContainsString( '@apply text-xs', $css );
	}

	public function test_extracts_tailwind_apply_classes_from_custom_css(): void {
		$classes = playbrick_extract_tailwind_apply_classes( ".t-c3 {\n  @apply text-white text-5xl font-bold;\n}" );

		$this->assertSame( [ 'font-bold', 'text-5xl', 'text-white' ], $classes );
	}

	public function test_collects_element_custom_css_from_bricks_content_rows(): void {
		$data = [
			[ 'id' => 'abc123', 'settings' => [ '_cssCustom' => '@apply grid gap-5;' ] ],
			[ 'id' => 'invalid', 'settings' => [ '_cssCustom' => '@apply hidden;' ] ],
		];

		$reflection = new \ReflectionFunction( 'playbrick_extract_tailwind_custom_css_from_bricks_data' );
		$css = $reflection->invoke( $data );

		$this->assertCount( 1, $css );
		$this->assertStringContainsString( '#brxe-abc123 {', $css[0] );
		$this->assertStringContainsString( '@apply grid gap-5;', $css[0] );
		$this->assertStringNotContainsString( 'hidden', $css[0] );
	}

	public function test_builds_theme_css_from_bricks_color_palette(): void {
		$palette = [
			[
				'id'     => 'pal1',
				'name'   => 'Main',
				'colors' => [
					[ 'id' => 'abc123', 'name' => 'Brand Amber', 'hex' => '#ffc107' ],
					[ 'id' => 'def456', 'name' => 'White', 'hex' => '#ffffff' ],
				],
