	}

	public function test_builds_theme_css_from_bricks_global_variables(): void {
		$variables = [
			[ 'id' => 'space1', 'name' => 'space-m', 'value' => 'clamp(1rem, 2vw, 2rem)', 'category' => 'Spacing' ],
			[ 'id' => 'text1', 'name' => 'text-xl', 'value' => 'clamp(1.5rem, 3vw, 2rem)', 'category' => 'Typography' ],
			[ 'id' => 'color1', 'name' => 'color-primary', 'value' => '#0f766e', 'category' => 'Colors' ],
			[ 'id' => 'radius1', 'name' => 'card-radius', 'value' => '20px', 'category' => 'Radii' ],
			[ 'id' => 'shadow1', 'name' => 'shadow-card', 'value' => '0 12px 30px rgb(0 0 0 / 0.12)', 'category' => 'Shadows' ],
			[ 'id' => 'leading1', 'name' => 'leading-normal', 'value' => '1.5', 'category' => 'Typography' ],
		];

		$css = playbrick_build_bricks_theme_css( [], $variables );

		$this->assertStringContainsString( '@theme inline {', $css );
		$this->assertStringContainsString( '--spacing-m: var(--space-m, clamp(1rem, 2vw, 2rem));', $css );
		$this->assertStringContainsString( '--text-xl: clamp(1.5rem, 3vw, 2rem);', $css );
		$this->assertStringContainsString( '--color-primary: #0f766e;', $css );
		$this->assertStringContainsString( '--radius-card: var(--card-radius, 20px);', $css );
		$this->assertStringContainsString( '--shadow-card: 0 12px 30px rgb(0 0 0 / 0.12);', $css );
		$this->assertStringContainsString( '--leading-normal: 1.5;', $css );
	}

	public function test_generates_grid_utilities_that_reference_bricks_variables(): void {
		$variables = [
			[ 'id' => 'columns1', 'name' => 'grid-template-columns-dashboard', 'value' => '16rem minmax(0, 1fr)' ],
			[ 'id' => 'rows1', 'name' => 'grid-template-rows-layout', 'value' => 'auto minmax(0, 1fr) auto' ],
			[ 'id' => 'invalid1', 'name' => 'grid-template-columns-', 'value' => '1fr' ],
			[ 'id' => 'other1', 'name' => 'grid-template-areas-dashboard', 'value' => '"nav main"' ],
		];

		$classes = playbrick_collect_bricks_global_variable_grid_utility_classes( $variables );
		$css     = playbrick_build_bricks_theme_css( [], $variables );
		$playground = sys_get_temp_dir() . '/playbrick-bricks-source/playground';
		$path = playbrick_write_bricks_tailwind_source( $playground, $classes, '', $css );

		$this->assertSame( [ 'grid-cols-dashboard', 'grid-rows-layout' ], $classes );
		$this->assertStringContainsString( '--grid-template-columns-dashboard: var(--grid-template-columns-dashboard);', $css );
		$this->assertStringContainsString( '--grid-template-rows-layout: var(--grid-template-rows-layout);', $css );
		$this->assertStringNotContainsString( 'grid-template-areas-dashboard', $css );
		$this->assertStringContainsString( 'grid-cols-dashboard grid-rows-layout', file_get_contents( $path ) );
	}

	public function test_builds_theme_css_skipping_malformed_global_variables(): void {
		$css = playbrick_build_bricks_theme_css(
			[],
			[
				'not-a-variable-array',
				[ 'name' => '', 'value' => '1rem' ],
				[ 'name' => 'space-empty', 'value' => '' ],
				[ 'name' => '-space-m', 'value' => '1rem' ],
				[ 'name' => 'space m', 'value' => '1rem' ],
				[ 'name' => 'bad:value', 'value' => '1rem' ],
				[ 'name' => 'text-bad', 'value' => '1rem; color: red' ],
				[ 'name' => 'unsupported-token', 'value' => '1rem' ],
				[ 'name' => 'space-m', 'value' => '1rem' ],
			]
		);

		$this->assertStringContainsString( '--spacing-m: var(--space-m, 1rem);', $css );
		$this->assertSame( 1, substr_count( $css, '--spacing-' ) );
		$this->assertStringNotContainsString( '--unsupported-token', $css );
		$this->assertStringNotContainsString( '--bad:value', $css );
		$this->assertStringNotContainsString( 'color: red', $css );
	}

